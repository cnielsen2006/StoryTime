import { useEffect, useMemo, useRef, useState, type ReactNode } from 'react';
import {
  kokoroAudio,
  kokoroVoiceLabel,
  readerAudio,
  sortKokoroVoices,
  unlockReaderAudio,
  useKokoro,
} from '../reading/kokoro.js';
import {
  DEFAULT_READING_SETTINGS,
  findVoice,
  formatSpeed,
  sortVoices,
  speechSupported,
  useReadingSettings,
  useVoices,
  voiceLabel,
  type ReadingEngine,
} from '../reading/settings.js';
import { Field } from './ui.js';

const SAMPLE =
  'The lamp in the window had been burning for three nights. On the fourth, someone finally knocked.';

/** Voice, speed and display preferences for reading the manuscript aloud. */
export function ReadingVoiceSection() {
  const [settings, update] = useReadingSettings();
  const kokoro = settings.engine === 'kokoro';
  const voices = useVoices();
  const { data: kokoroInfo, error: kokoroError } = useKokoro(kokoro);
  const [allLanguages, setAllLanguages] = useState(false);
  const [previewing, setPreviewing] = useState(false);
  const [previewError, setPreviewError] = useState<string | null>(null);
  const previewToken = useRef(0);
  const sectionRef = useRef<HTMLElement>(null);

  const language = (navigator.language || 'en').split('-')[0]!.toLowerCase();
  const sorted = useMemo(() => sortVoices(voices), [voices]);
  const kokoroVoices = useMemo(() => sortKokoroVoices(kokoroInfo?.voices ?? []), [kokoroInfo]);
  const selected = findVoice(voices, settings.voiceURI);
  const shown = allLanguages
    ? sorted
    : sorted.filter((v) => v.lang.toLowerCase().startsWith(language) || v.voiceURI === settings.voiceURI);

  // The read-aloud bar links here with #reading.
  useEffect(() => {
    if (window.location.hash === '#reading') sectionRef.current?.scrollIntoView({ block: 'start' });
  }, []);

  const stopPreview = () => {
    previewToken.current += 1;
    if (speechSupported) window.speechSynthesis.cancel();
    readerAudio().pause();
    setPreviewing(false);
  };

  useEffect(() => stopPreview, []);

  const previewBrowser = () => {
    const synth = window.speechSynthesis;
    synth.cancel();
    const utterance = new SpeechSynthesisUtterance(SAMPLE);
    if (selected) {
      utterance.voice = selected;
      utterance.lang = selected.lang;
    }
    utterance.rate = settings.rate;
    utterance.pitch = settings.pitch;
    utterance.volume = settings.volume;
    utterance.onend = utterance.onerror = () => setPreviewing(false);
    setPreviewing(true);
    synth.speak(utterance);
  };

  const previewKokoro = () => {
    const token = ++previewToken.current;
    unlockReaderAudio();
    setPreviewing(true);
    kokoroAudio(SAMPLE, settings.kokoroVoice).then(
      (url) => {
        if (previewToken.current !== token) return;
        const audio = readerAudio();
        audio.src = url;
        audio.defaultPlaybackRate = settings.rate;
        audio.playbackRate = settings.rate;
        audio.volume = settings.volume;
        audio.onended = () => {
          if (previewToken.current === token) setPreviewing(false);
        };
        audio.play().catch(() => setPreviewing(false));
      },
      (err: unknown) => {
        if (previewToken.current !== token) return;
        setPreviewing(false);
        setPreviewError(err instanceof Error ? err.message : String(err));
      },
    );
  };

  const preview = () => {
    setPreviewError(null);
    if (kokoro) previewKokoro();
    else previewBrowser();
  };

  const kokoroStatus =
    kokoroError instanceof Error
      ? `The StoryTime server could not be reached for Kokoro voices: ${kokoroError.message}`
      : kokoroInfo?.status === 'loading'
        ? 'Loading the Kokoro voice model. The first time, this downloads about 90 MB and can take a minute or two.'
        : kokoroInfo?.status === 'error'
          ? `The Kokoro voice model failed to load: ${kokoroInfo.error ?? 'unknown error'}. It will try again when you press Listen.`
          : 'Kokoro runs on the StoryTime server, so these voices sound the same on every device.';

  return (
    <section id="reading" ref={sectionRef} className="mt-10 space-y-4 border-t border-ink-200 pt-8">
      <div>
        <h2 className="text-base font-semibold text-ink-900">Reading voice</h2>
        <p className="mt-1 text-sm text-ink-500">
          Press Listen above any chapter to hear it read aloud. These settings are saved in this browser and not
          shared with other devices.
        </p>
      </div>

      <Field label="Voice engine">
        <div className="space-y-1.5">
          <EngineOption engine="kokoro" current={settings.engine} onChange={(engine) => update({ engine })}>
            <span className="font-medium">Kokoro</span>
            <span className="text-ink-500"> — natural-sounding voices generated by the StoryTime server</span>
          </EngineOption>
          <EngineOption engine="browser" current={settings.engine} onChange={(engine) => update({ engine })}>
            <span className="font-medium">Browser voices</span>
            <span className="text-ink-500"> — whatever this device provides; works without the server's help</span>
          </EngineOption>
        </div>
      </Field>

      {kokoro ? (
        <Field label="Voice" hint={kokoroStatus}>
          <select
            className="field"
            value={settings.kokoroVoice}
            onChange={(e) => update({ kokoroVoice: e.target.value })}
          >
            {kokoroVoices.length === 0 ? <option value={settings.kokoroVoice}>{settings.kokoroVoice}</option> : null}
            {kokoroVoices.map((voice) => (
              <option key={voice.id} value={voice.id}>
                {kokoroVoiceLabel(voice)}
              </option>
            ))}
          </select>
        </Field>
      ) : !speechSupported ? (
        <p className="rounded-md border border-amber-200 bg-amber-50 px-3 py-2 text-sm text-amber-800">
          This browser cannot read text aloud with its own voices. Try Kokoro, or a current version of Chrome, Edge,
          Safari or Firefox.
        </p>
      ) : (
        <>
          <Field
            label="Voice"
            hint={
              voices.length === 0
                ? 'No voices found yet. Some browsers load them a moment after the page opens.'
                : 'Voices marked online need a network connection and usually sound more natural.'
            }
          >
            <select
              className="field"
              value={settings.voiceURI}
              onChange={(e) => update({ voiceURI: e.target.value })}
            >
              <option value="">Browser default</option>
              {shown.map((voice) => (
                <option key={voice.voiceURI} value={voice.voiceURI}>
                  {voiceLabel(voice)}
                </option>
              ))}
            </select>
            <label className="mt-2 flex items-center gap-2 text-xs text-ink-500">
              <input type="checkbox" checked={allLanguages} onChange={(e) => setAllLanguages(e.target.checked)} />
              Show voices for every language ({voices.length} available)
            </label>
          </Field>

          {settings.voiceURI && voices.length > 0 && !selected ? (
            <p className="text-xs text-amber-700">
              The saved voice is not available on this device, so the browser default is used instead.
            </p>
          ) : null}
        </>
      )}

      {kokoro || speechSupported ? (
        <>
          <Slider
            label="Speed"
            value={settings.rate}
            min={0.5}
            max={2}
            step={0.05}
            display={formatSpeed(settings.rate)}
            onChange={(rate) => update({ rate })}
          />
          {kokoro ? null : (
            <Slider
              label="Pitch"
              value={settings.pitch}
              min={0.5}
              max={1.5}
              step={0.05}
              display={settings.pitch === 1 ? 'Normal' : settings.pitch.toFixed(2)}
              onChange={(pitch) => update({ pitch })}
            />
          )}
          <Slider
            label="Volume"
            value={settings.volume}
            min={0}
            max={1}
            step={0.05}
            display={`${Math.round(settings.volume * 100)}%`}
            onChange={(volume) => update({ volume })}
          />

          <div className="space-y-2">
            <Toggle checked={settings.highlight} onChange={(highlight) => update({ highlight })}>
              Highlight the paragraph being read
            </Toggle>
            <Toggle checked={settings.autoScroll} onChange={(autoScroll) => update({ autoScroll })}>
              Scroll to follow along
            </Toggle>
            <Toggle checked={settings.continueToNext} onChange={(continueToNext) => update({ continueToNext })}>
              Carry on to the next chapter when one finishes
            </Toggle>
          </div>

          <div className="flex items-center gap-2">
            {previewing ? (
              <button className="btn-secondary" onClick={stopPreview}>
                Stop
              </button>
            ) : (
              <button className="btn-secondary" onClick={preview}>
                Preview voice
              </button>
            )}
            <button className="btn-ghost" onClick={() => update(DEFAULT_READING_SETTINGS)}>
              Reset to defaults
            </button>
          </div>
          {previewError ? <p className="text-xs text-red-600">{previewError}</p> : null}
        </>
      ) : null}
    </section>
  );
}

function EngineOption({
  engine,
  current,
  onChange,
  children,
}: {
  engine: ReadingEngine;
  current: ReadingEngine;
  onChange: (engine: ReadingEngine) => void;
  children: ReactNode;
}) {
  return (
    <label className="flex items-start gap-2 text-sm text-ink-700">
      <input
        type="radio"
        name="reading-engine"
        className="mt-1"
        checked={current === engine}
        onChange={() => onChange(engine)}
      />
      <span>{children}</span>
    </label>
  );
}

function Slider({
  label,
  value,
  min,
  max,
  step,
  display,
  onChange,
}: {
  label: string;
  value: number;
  min: number;
  max: number;
  step: number;
  display: string;
  onChange: (value: number) => void;
}) {
  return (
    <div>
      <div className="flex items-baseline justify-between">
        <label className="label">{label}</label>
        <span className="text-xs text-ink-500 tabular-nums">{display}</span>
      </div>
      <input
        type="range"
        className="w-full accent-ink-700"
        min={min}
        max={max}
        step={step}
        value={value}
        aria-label={label}
        onChange={(e) => onChange(Number(e.target.value))}
      />
    </div>
  );
}

function Toggle({
  checked,
  onChange,
  children,
}: {
  checked: boolean;
  onChange: (checked: boolean) => void;
  children: ReactNode;
}) {
  return (
    <label className="flex items-center gap-2 text-sm text-ink-700">
      <input type="checkbox" checked={checked} onChange={(e) => onChange(e.target.checked)} />
      {children}
    </label>
  );
}
